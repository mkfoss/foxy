package core

import (
	"fmt"
	"testing"

	"github.com/mkfoss/foxy/internal/mockfiler"
	"github.com/stretchr/testify/assert"
)

func Test_RedFieldDef(t *testing.T) {

	type testcase struct {
		id       int
		input    []byte
		expected *FieldDef
		err      string
	}

	testcases := []*testcase{
		{1,
			[]byte{0x49, 0x46, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x49, 0x01, 0x00, 0x00, 0x00,
				0x04, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
			&FieldDef{
				FieldName: [11]byte{0x49, 0x46, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
				FieldType: 0x49,
				Offset:    1,
				Length:    4,
				Decimals:  0,
				Flags:     0x04,
				Reserved:  [13]byte{},
			},
			"",
		},
		{2,
			[]byte{0x43, 0x46, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x43, 0x05, 0x00, 0x00, 0x00,
				0x0A, 0x00, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
			&FieldDef{
				FieldName: [11]byte{0x43, 0x46, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
				FieldType: 0x43,
				Offset:    5,
				Length:    10,
				Decimals:  0,
				Flags:     0x02,
				Reserved:  [13]byte{},
			},
			"",
		},
		{3,
			[]byte{0x46, 0x46, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x4E, 0x0F, 0x00, 0x00, 0x00,
				0x08, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
			&FieldDef{
				FieldName: [11]byte{0x46, 0x46, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
				FieldType: 0x4E,
				Offset:    15,
				Length:    8,
				Decimals:  4,
				Flags:     0x00,
				Reserved:  [13]byte{},
			},
			"",
		},
	}

	for _, tc := range testcases {
		t.Run(fmt.Sprintf("RedFieldDef #%.2d", tc.id), func(t *testing.T) {
			fl := &mockfiler.MockFiler{
				Data: tc.input,
				Pos:  0,
			}
			defer func() { _ = fl.Close() }()

			got, err := ReadFieldDef(fl)
			if tc.err != "" {
				if err == nil {
					t.Fatalf("ReadFieldDef expected error but got nil")
				}
				assert.ErrorContains(t, err, tc.err)
			} else {
				if err != nil {
					t.Fatalf("ReadFieldDef expected no error but got %s", err)
				}
				assert.Equal(t, tc.expected, got)
			}
		})
	}
}
